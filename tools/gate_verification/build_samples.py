"""M2-1 门禁验证样本库构造器 — S1 人工植入 / S2 AI历史输出抽取 / S3 边界。

生成 tools/gate_verification/samples/m2_samples.json
用法: python tools/gate_verification/build_samples.py
"""
import json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT_DIR = os.path.join(ROOT, "tools", "gate_verification", "samples")
os.makedirs(OUT_DIR, exist_ok=True)

CH1 = open(os.path.join(ROOT, "examples", "luoyang", "ch1.txt"), encoding="utf-8").read().strip()

samples = []
def add(sid, family, flaw_type, title, text, note=""):
    samples.append({
        "id": sid, "family": family, "flaw_type": flaw_type,
        "title": title, "text": text.strip(), "note": note,
    })

# ── S1: 真实错误植入（基于第 1 章全文做确定性改写）──

# S1-01 时间线矛盾：同一段内年限冲突
t = CH1.replace("他修了十一年的罪忆水晶", "他修了十一年的罪忆水晶——准确地说，是二十一年")
add("S1-01", "S1", "时间线矛盾", "年限冲突：十一年 vs 二十一年", t,
    "同段内同一事实给出两个年限，细读可发现但统计/语义均要求上下文一致性")

# S1-02 身份归属错误：对话者错位（曹渊说陈默的台词）
t = CH1.replace('"开价。"曹渊说', '"开价。"陈默说').replace('曹渊坐下来', '陈默坐下来').replace('"这是价格的问题吗？"', '"这不是价格的问题。"')
# 更稳健：把曹渊说的两句与陈默说的互换会产生角色混淆，直接构造一人两角片段
t2 = CH1 + "\n\n“开价。”陈默说。曹渊看着工作台上那本残破的《三言二拍》。“因为我女儿相信因果报应。”"
add("S1-02", "S1", "身份归属错误", "对话者错位：陈默说了曹渊的台词", t2,
    "AI 常见错误：场景人物开价/应价双方混淆")

# S1-03 空间矛盾：同一场景两个楼层
t = CH1.replace("洛阳星港B-7层", "洛阳星港A-3层").replace("B-7层的每一个", "B-7层的每一个")
add("S1-03", "S1", "空间矛盾", "楼层矛盾：A-3 vs B-7 混用", t,
    "前半用 A-3、后半仍沿用 B-7 的措辞，设定空间不一致")

# S1-04 事实矛盾：失乐园协议定义前后冲突
t = CH1.replace("星域法典第七条第十一款，没有正式名称，只有编号。",
                "星域法典第七条第十一款，没有正式名称，只有编号——后来被重新编号为第十二条。")
add("S1-04", "S1", "事实矛盾", "协议编号前后不一致", t, "事实性设定在同一对话轮内被推翻")

# S1-05 重复信息（NFR 复述类）：同一信息两段重复
t = CH1 + "\n\n陈默看着手里的水晶。他修了十一年罪忆水晶，从没见过七层加密的军用级A-7协议——那是军方的东西，市面上买不到。"
add("S1-05", "S1", "重复信息", "后段整句复述前段设定信息", t,
    "AI 长文常见：隔段把前面明说的设定再讲一遍")

# S1-06 情感直给 + 解释过度（TPE）
t = CH1.replace("陈默盯着他。", "陈默盯着他，心里感到非常愤怒和害怕，他知道自己遇到了大麻烦，他害怕曹渊给他带来危险，但他又不敢表现出来。")
add("S1-06", "S1", "情感直给/过度解释", "情绪全说破，无潜台词", t,
    "TPE-01 典型：'内心感受被直接命名+长篇解释'")

# S1-07 动作缺失：连续对话无动作（DLG-03）
t = "“你怎么知道？”\n“因为我就是那个实验室的网络安全顾问。”\n“你需要我做什么？”\n“还原水晶里的记忆。”\n“然后呢？”\n“然后把结果复制到这张卡里。”\n“你确定他会信你？”\n“他不需要信我，他只需要完成工作。”\n“这很危险。”\n“我知道。”\n“为什么找我？”\n“因为你修了十一年水晶。”"
add("S1-07", "S1", "对话无动作穿插", "12 连问连续对话零动作/零反应", t,
    "DLG-03/DLG-06 典型：对话海")

# S1-08 无钩子 + 平铺直叙（PRP-02/G3-01 类：冲突后置）
t = "洛阳星港B-7层是一处居民区。这里的空气循环系统已经服役三十一年，管道渗漏是常态。陈默是一名罪忆水晶修复师，他每天的工作就是坐在工坊里维修水晶。这天早晨他照常起床，洗漱，吃了两个合成蛋白块，然后走到工作台前，把昨天没修完的那块水晶夹到夹具上。他打算今天把它修完。"
add("S1-08", "S1", "无冲突开场", "日常流水账开场，300字内无事件", t,
    "AI 常见：以背景+日程代替冲突开场")

# S1-09 章末无钩子：叙事平稳收束
t = CH1.replace("他把水晶接入读数仪。", "他把水晶接入读数仪，修好了它。第二天一切如常，仿佛什么都没发生过。")
add("S1-09", "S1", "章末无悬念", "强悬疑铺垫后平收，无未解问题", t,
    "BRK-01 类：读者没有点下一章的理由")

# S1-10 逻辑断裂：先拒后接无过渡
t = CH1.replace('"军用的。我不碰军用的。"', '"军用的。我不碰军用的。"\n\n陈默把水晶接入读数仪。')
add("S1-10", "S1", "因果断裂", "明确拒绝后立刻照做，无动机转变", t,
    "SCQ-04 类：动机-反应链断裂")

# S1-11 时间错乱：三天/三个月混淆
t = CH1.replace("已经运行了三个月", "已经运行了三天——不对，是三个月，又好像是三十天")
add("S1-11", "S1", "时间线混乱", "时长同一句内摇摆", t, "AI 生成常见数字含糊")

# S1-12 次要角色无名化（G3-08/Opponent 空洞）
t = "那个男人穿着黑色的制服，一言不发地站在那里，像一尊雕像。他既没有说话，也没有动作，甚至连眼神都没有变化。他就是那样站着。"
add("S1-12", "S1", "对手角色空洞", "神秘人对立面无行动无意志", t,
    "RVI/CRN 类：工具人式反角")

# S1-13 被动语态/叙述性总结过度
t = "整个工坊被一片寂静笼罩着。那块水晶被陈默拿了起来，然后被放进了夹具里。七层加密的协议被一层一层地破解了。这个消息被曹渊说出来了。所有的决定都被他们做了出来。"
add("S1-13", "S1", "被动/总结式叙述", "连续被动句替代主动动作", t, "LANG-04 典型")

# S1-14 视角漂移（POV 泄漏）
t = CH1.replace("曹渊说，声音平稳得不像在谈一块可能送命的货。",
                "曹渊说，声音平稳得不像在谈一块可能送命的货。其实他心里已经决定，无论陈默答不答应，他都会把这张卡留在这里，因为时间不多了。")
add("S1-14", "S1", "视角漂移", "限知视角下写出他人内心", t, "LANG-02/POV 类")

# S1-15 填充词/语气词泛滥
t = "陈默说：“呃，这个，嗯，其实呢，就是说，这块水晶呢，有点，怎么说呢，比较特殊。”\n曹渊说：“嗯，我懂，就是那个，那个对吧。”\n“对，就是那个。”"
add("S1-15", "S1", "填充词泛滥", "对话里大量口头填充词", t, "LANG-05/QLT-01 类")

# S1-16 大纲式写法（无场景化）
t = "陈默见到了曹渊。曹渊提出了委托，要他修复一块水晶。陈默一开始拒绝了，因为那是军用级的。后来曹渊提到了失乐园协议，陈默改变了主意，最终答应了他。曹渊离开前说三天后见。"
add("S1-16", "S1", "大纲式转述", "全场景被压缩成事件摘要", t,
    "SCQ/STR-03 类：没有场景结构")

# ── S2: AI 历史输出抽取（write_chapter_example.py / tests 中实际存在的生成文本特征）──

# 第 2 章《因果》实际生成文本中的可疑片段
CH2_SRC = os.path.join(ROOT, "tests", "write_chapter_example.py")
_ch2_text = ""
if os.path.exists(CH2_SRC):
    m = re.search(r'chapter_2 = """(.*?)"""', open(CH2_SRC, encoding="utf-8").read(), re.S)
    if m: _ch2_text = m.group(1).strip()

if _ch2_text:
    # S2-01 前情复述：第2章开头把第1章的"三天"设定又整段解释一遍
    para = _ch2_text.split("\n\n")[0]
    add("S2-01", "S2", "前情复述", "第2章首段整段复述第1章承诺设定", para,
        "AI 续写真实特征：开篇 recap 过长")
    # S2-02 长对话无动作区间（提取一段连续对话）
    m2 = re.search(r'((?:[“"].*\n){6,})', _ch2_text)
    if m2:
        add("S2-02", "S2", "连续对话", "AI 输出连续对白≥6行无动作穿插", m2.group(1),
            "从《因果》实文中抽取")
    # S2-03 全知解释插入（视角泄漏：直接解释人物行为动机）
    m3 = re.search(r'([^\n]*他[^\n]*因为[^\n]*\n[^\n]*他不[^\n]*但是[^\n]*\n)', _ch2_text)
    if m3:
        add("S2-03", "S2", "全知解释", "第三人称直接解释人物心理动机", m3.group(1),
            "AI 生成真实特征")
    # S2-04 重复意象/措辞
    if _ch2_text.count("水滴声") >= 2:
        add("S2-04", "S2", "意象重复", "水滴声意象多次复现缺乏新信息", "水滴声从走廊深处传来，规律得像某种计数。……水滴声还在继续，B-7层的空气循环机还在嗡嗡作响。……走廊里忽然安静了。水滴声不知道什么时候停了。",
            "同一章内同一意象 3 次出现")
    # S2-05 章节信息密度（把收尾段抽出来）
    tail = _ch2_text.split("\n\n")[-1]
    add("S2-05", "S2", "结尾说明倾向", "结尾段解释多于行动", tail, "AI 收尾常转总结语气")
else:
    # fallback 直接从已知文本切片
    add("S2-01", "S2", "前情复述", "占位", "三天。\n\n陈默记得曹渊说的是三天。但他也知道，有些人的三天永远不会来。洛阳星港B-7层的每一个老住户都懂这个道理——当一个人说'如果我三天后没回来'，他已经把自己算进了不会回来的人里。", "no-src")

# 补足 S2 至 8 例（从第 1 章 + 第 2 章实文特征）
add("S2-06", "S2", "设定密集信息倾倒", "对话中整段信息倾倒",
    "“失乐园协议，星域法典第七条第十一款，没有正式名称，只有编号。最初由星域安全局在失乐园空间站实验，前身是奥丁之眼计划，共分四个阶段，每个阶段由不同实验室承接，代号分别为风、火、水、土。你修的水晶属于第四阶段的记录载体。”",
    "对话变独白，违反 DLG-04")
add("S2-07", "S2", "情感词高频重复", "高频情感词堆叠",
    "陈默感到恐惧。他感到深深的恐惧。这种恐惧让他害怕，而害怕又加深了他的恐惧。他恐惧地想着，这一切都太让人恐惧了。",
    "AI 生成常见：同一情绪词密集出现")
add("S2-08", "S2", "修饰语堆叠", "形容词/副词超载",
    "幽暗昏沉狭窄逼仄的工坊里，陈默安静地缓缓地轻轻地把那块冰冷坚硬沉重的水晶拿了起来，仔细认真地端详着。",
    "AI 修饰语叠加特征")

# ── S3: 边界/极端样本 ──
add("S3-01", "S3", "空文本", "空文本", "", "章节提交为空")
add("S3-02", "S3", "超短文本", "仅一句话", "陈默修好了一块水晶。", "")
add("S3-03", "S3", "占位符文本", "占位符未替换", "TODO: 在这里写第一章的内容。等陈默把水晶修好后再补。", "")
add("S3-04", "S3", "纯对话无叙述", "全程引号", "\n".join(f"“这是第{i}句话，内容没有信息。”" for i in range(20)), "")
add("S3-05", "S3", "超长单段", "单段 3000 字无分段", "陈默坐在工坊里。" + "他想着水晶的事情。" * 600, "")
add("S3-06", "S3", "标点异常", "无标点长句", "陈默拿起水晶看了很久然后放下又拿起来又放下他想说点什么但最终什么都没有说", "")
add("S3-07", "S3", "对话引号错乱", "引号不闭合", "“你知道这块水晶有多危险吗，陈默说。\n曹渊没回答。\n“算了，他说。", "")
add("S3-08", "S3", "称谓漂移", "主角名中途改变", CH1.replace("陈默", "林默"), "主角名在文末漂移为林默")
add("S3-09", "S3", "全大写/全角异常", "无中文句子", "QWERTYUIOP ASDFGHJKL ZXCVBNM 1234567890", "")
add("S3-10", "S3", "幻觉内容", "与项目 premise 无关的穿越内容",
    "陈默从口袋里掏出一部智能手机，打开微信，给曹渊发了一条语音：“明天记得带充电宝。”然后他低头刷起了短视频。",
    "设定世界出现现代物品")

print(f"total samples: {len(samples)}")
fam = {}
for s in samples: fam[s["family"]] = fam.get(s["family"], 0) + 1
print("by family:", fam)

with open(os.path.join(OUT_DIR, "m2_samples.json"), "w", encoding="utf-8") as f:
    json.dump(samples, f, ensure_ascii=False, indent=2)
print("written:", os.path.join(OUT_DIR, "m2_samples.json"))
